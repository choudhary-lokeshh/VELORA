/**
 * Every Android permission this application may ship, and why.
 *
 * There are two manifests and they say different things. The one in
 * `apps/mobile/android/app/src/main/AndroidManifest.xml` is what this
 * repository declares. The one inside the built APK is that manifest *merged*
 * with the manifest of every library in the graph, and it is the only one a
 * person installing the application ever meets.
 *
 * That gap is not academic. The declared manifest asked for six permissions;
 * the first release APK built from it asked for thirty-two — Firebase Cloud
 * Messaging's three, two biometric permissions from a secure-storage feature
 * nothing uses, Play's install-referrer binding, and sixteen launcher-badge
 * permissions for Samsung, Huawei, HTC, Sony, Oppo and four other OEMs. None
 * of it appeared in any file in this repository.
 *
 * So both are checked, against this one table:
 *
 * - `pnpm android:verify` asserts the **declared** manifest. It compiles
 *   nothing and runs everywhere, inside `pnpm ci:verify`.
 * - `pnpm android:build` asserts the **merged** manifest, read back out of the
 *   built artifact. It needs a toolchain and runs as its own CI job.
 *
 * Neither replaces the other. The first catches a permission somebody wrote
 * down; the second catches a permission a dependency brought.
 */

